            Vector2[] treePositions = new[]
            {
                new Vector2(-5,  4),
                new Vector2( 6,  3),
                new Vector2(-3, -4),
                new Vector2( 4, -5),
                new Vector2(-7,  0),
                new Vector2( 7,  0),
                new Vector2( 0,  6),
